'use strict';

const fs = require('fs');

const args = process.argv.slice(2);

function usage() {
  console.error(`Usage:
  node source/js/leancloud-counter-to-umami-sql.js Counter.json \\
    --website-id <umami-website-id> \\
    --hostname <blog-hostname> \\
    --created-at 2024-01-01T00:00:00Z \\
    --site-pv-path __legacy_site_pv \\
    --session-count 1000 > umami-legacy-pageviews.sql

Notes:
  --session-count controls imported visitors/visits approximation.
  If omitted, the script uses LeanCloud site-uv when present, otherwise 1.
  If the export has no page paths, site-pv is imported as --site-pv-path.
`);
  process.exit(1);
}

function takeOption(name) {
  const index = args.indexOf(name);
  if (index === -1) return null;
  const value = args[index + 1];
  if (!value || value.startsWith('--')) usage();
  args.splice(index, 2);
  return value;
}

const inputFile = args[0];
const websiteId = takeOption('--website-id');
const hostname = takeOption('--hostname') || '';
const createdAt = takeOption('--created-at') || '2024-01-01T00:00:00Z';
const sitePVPath = takeOption('--site-pv-path') || '__legacy_site_pv';
const sessionCountOption = takeOption('--session-count');

if (!inputFile || !websiteId) {
  usage();
}

const input = JSON.parse(fs.readFileSync(inputFile, 'utf8'));

function getRows(data) {
  if (Array.isArray(data)) return data;
  if (Array.isArray(data.results)) return data.results;
  if (Array.isArray(data.Counter)) return data.Counter;

  const arrayValue = Object.values(data).find(Array.isArray);
  return arrayValue || [];
}

function getValue(row, key) {
  return row[key] ?? (row._serverData && row._serverData[key]);
}

function normalizePath(target) {
  if (!target || target === 'site-pv' || target === 'site-uv') {
    return null;
  }

  const path = String(target);

  if (path === '/') {
    return path;
  }

  return path.startsWith('/') ? path : `/${path}`;
}

function sqlString(value) {
  return "'" + String(value).replace(/'/g, "''") + "'";
}

function sqlNumber(value) {
  const number = Number(value);
  return Number.isFinite(number) && number > 0 ? Math.floor(number) : 0;
}

const counters = new Map();
let sitePV = 0;
let siteUV = 0;

for (const row of getRows(input)) {
  const target = getValue(row, 'target');
  const time = sqlNumber(getValue(row, 'time'));

  if (!target || time <= 0) continue;

  if (target === 'site-uv') {
    siteUV += time;
    continue;
  }

  if (target === 'site-pv') {
    sitePV += time;
    continue;
  }

  const path = normalizePath(target);

  if (!path) continue;

  counters.set(path, (counters.get(path) || 0) + time);
}

const rows = Array.from(counters, ([path, pageviews]) => ({ path, pageviews }));

if (rows.length === 0 && sitePV > 0) {
  rows.push({ path: sitePVPath, pageviews: sitePV });
}

const totalPageviews = rows.reduce((sum, row) => sum + row.pageviews, 0);
const requestedSessionCount = sessionCountOption ? sqlNumber(sessionCountOption) : siteUV;
const sessionCount = Math.max(1, Math.min(requestedSessionCount || 1, totalPageviews || 1));

console.log('-- Generated by source/js/leancloud-counter-to-umami-sql.js');
console.log('-- Import type: LeanCloud Counter -> Umami v3 website_event pageviews');
console.log(`-- Website ID: ${websiteId}`);
console.log(`-- Hostname: ${hostname || '(empty)'}`);
console.log(`-- Imported paths: ${rows.length}`);
console.log(`-- Imported pageviews: ${totalPageviews}`);
console.log(`-- Imported sessions/visitors approximation: ${sessionCount}`);
console.log('');
console.log('BEGIN;');
console.log('CREATE EXTENSION IF NOT EXISTS pgcrypto;');
console.log('');
console.log('-- Roll back a previous run of this import tag before inserting again.');
console.log("DELETE FROM website_event WHERE website_id = " + sqlString(websiteId) + " AND tag = 'legacy-leancloud';");
console.log(
  "DELETE FROM \"session\" WHERE website_id = " +
    sqlString(websiteId) +
    " AND distinct_id LIKE 'legacy-leancloud-%' AND NOT EXISTS (SELECT 1 FROM website_event WHERE website_event.session_id = \"session\".session_id);"
);
console.log('');
console.log('CREATE TEMP TABLE _umami_import_counter (url_path text PRIMARY KEY, pageviews integer NOT NULL);');

if (rows.length > 0) {
  console.log('INSERT INTO _umami_import_counter (url_path, pageviews) VALUES');
  rows.forEach((row, index) => {
    const suffix = index === rows.length - 1 ? ';' : ',';
    console.log(`  (${sqlString(row.path)}, ${row.pageviews})${suffix}`);
  });
}

console.log('');
console.log('CREATE TEMP TABLE _umami_import_session AS');
console.log('SELECT');
console.log('  row_number() OVER () AS idx,');
console.log('  gen_random_uuid() AS session_id,');
console.log('  gen_random_uuid() AS visit_id');
console.log(`FROM generate_series(1, ${sessionCount});`);
console.log('');
console.log('INSERT INTO "session" (session_id, website_id, browser, os, device, screen, language, distinct_id, created_at)');
console.log('SELECT');
console.log('  session_id,');
console.log(`  ${sqlString(websiteId)}::uuid,`);
console.log("  'Chrome',");
console.log("  'Windows',");
console.log("  'desktop',");
console.log("  '1920x1080',");
console.log("  'zh-CN',");
console.log("  'legacy-leancloud-' || idx,");
console.log(`  ${sqlString(createdAt)}::timestamptz`);
console.log('FROM _umami_import_session;');
console.log('');
console.log('WITH expanded AS (');
console.log('  SELECT');
console.log('    c.url_path,');
console.log('    row_number() OVER (ORDER BY c.url_path, n) AS rn');
console.log('  FROM _umami_import_counter c');
console.log('  CROSS JOIN LATERAL generate_series(1, c.pageviews) AS n');
console.log(')');
console.log('INSERT INTO website_event (');
console.log('  event_id, website_id, session_id, visit_id, created_at,');
console.log('  url_path, page_title, event_type, hostname, tag');
console.log(')');
console.log('SELECT');
console.log('  gen_random_uuid(),');
console.log(`  ${sqlString(websiteId)}::uuid,`);
console.log('  s.session_id,');
console.log('  s.visit_id,');
console.log(`  ${sqlString(createdAt)}::timestamptz + (((e.rn - 1) % 86400) * interval '1 second'),`);
console.log('  e.url_path,');
console.log('  e.url_path,');
console.log('  1,');
console.log(`  ${sqlString(hostname)},`);
console.log("  'legacy-leancloud'");
console.log('FROM expanded e');
console.log(`JOIN _umami_import_session s ON s.idx = ((e.rn - 1) % ${sessionCount}) + 1;`);
console.log('');
console.log("SELECT 'legacy sessions' AS label, count(*) FROM \"session\" WHERE website_id = " + sqlString(websiteId) + " AND distinct_id LIKE 'legacy-leancloud-%';");
console.log("SELECT 'legacy pageviews' AS label, count(*) FROM website_event WHERE website_id = " + sqlString(websiteId) + " AND tag = 'legacy-leancloud';");
console.log('');
console.log('COMMIT;');
